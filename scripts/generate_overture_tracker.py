#!/usr/bin/env python3
"""Generate spreadsheet-friendly overture and Assembly action-trail trackers."""

from __future__ import annotations

import csv
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path


ROOT = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
DOCS = ROOT / "docs"
INDEX = ROOT / "index"
TRACKER_DIR = DOCS / "overture-tracker"
GATE_FILE = TRACKER_DIR / "assembly-gates.yaml"
RECORD_OUT = TRACKER_DIR / "overtures.csv"
ASSEMBLY_OUT = TRACKER_DIR / "assemblies.csv"
QUEUE_OUT = TRACKER_DIR / "work-queue.csv"
INVENTORY_RECONCILIATION = TRACKER_DIR / "inventory-reconciliation.csv"
TRACKER_OUT = DOCS / "overture-action-tracker.yaml"


def read_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    rows = []
    for line_no, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if line.strip():
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError as exc:
                raise SystemExit(f"{path}:{line_no}: {exc}") from exc
    return rows


def read_gates() -> dict:
    # The gate file is JSON, which is a strict subset of YAML. This keeps the
    # hand-maintained YAML input readable without adding a parser dependency.
    contents = "\n".join(
        line for line in GATE_FILE.read_text(encoding="utf-8").splitlines()
        if not line.lstrip().startswith("#")
    )
    return json.loads(contents)


def ga_from_volume(vol: str) -> int | None:
    match = re.match(r"ga(\d+)_", vol or "")
    return int(match.group(1)) if match else None


def csv_write(path: Path, fields: list[str], rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def yaml_scalar(value) -> str:
    """Quote scalars with JSON string syntax, which is valid YAML 1.2."""
    if value is None:
        return '""'
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return json.dumps(str(value), ensure_ascii=False)


def write_hierarchical_tracker(assemblies: list[dict], records_by_ga: dict[int, list[dict]],
                               queue_rows: list[dict], path: Path) -> None:
    """Write the main tracker as GA packets, with each overture under its GA."""
    next_step_by_ga = {
        int(row["assembly"][2:]): row["next_step"]
        for row in queue_rows if row["scope"] in ("assembly_packet", "pending_follow_up")
    }
    lines = [
        "# Generated by scripts/generate_overture_tracker.py; edit source ledgers instead.",
        "# GA status is packet progress; overture status is research progress.",
        "assemblies:",
    ]
    assembly_fields = [
        "ga_ordinal", "assembly", "status", "catalogue_records", "records_complete",
        "records_in_progress", "records_not_researched", "records_source_unavailable",
        "missing_research_rows", "missing_event_bundles", "candidate_passages",
        "candidates_reviewed", "candidates_unreviewed", "candidate_invalid_links",
        "candidate_reviews_orphaned", "roster_reconciled", "event_source_audited",
        "build", "preview_reviewed", "commit_sha", "pushed", "blocker",
    ]
    overture_fields = [
        "record_id", "number", "source_page", "source", "title", "page",
        "research_status", "next_step", "disposition", "event_count", "last_action_ga",
        "search_through_assembly", "gap_note", "anomalies",
    ]
    for assembly in assemblies:
        ga = assembly["ga_ordinal"]
        lines.append("  -")
        for field in assembly_fields:
            lines.append(f"    {field}: {yaml_scalar(assembly.get(field, ''))}")
        lines.append(f"    next_step: {yaml_scalar(next_step_by_ga.get(ga, ''))}")
        lines.append("    overtures:")
        for record in sorted(records_by_ga.get(ga, []),
                             key=lambda row: (int(row["number"] or 0), row["record_id"])):
            lines.append("      -")
            for field in overture_fields:
                value = record.get(field, "")
                lines.append(f"        {field}: {yaml_scalar(value)}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def catalogue_rows(path: Path, page_map: dict) -> dict[str, dict]:
    """Read catalogue presentation fields so catalogue-only rows stay legible."""
    result = {}
    link_pattern = re.compile(r"\]\(\.\./overtures/([^\)#]+\.md)\)")
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            continue
        match = link_pattern.search(line)
        if not match:
            continue
        target = "overtures/" + match.group(1)
        record_ids = [rid for rid, mapped_path in page_map.items()
                      if rid.startswith("overture:") and mapped_path == target]
        if not record_ids:
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) < 4:
            continue
        clean = lambda value: re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", value)
        for record_id in record_ids:
            result[record_id] = {
                "title": clean(cells[1]),
                "disposition": clean(cells[2]),
                "source": clean(cells[3]),
            }
    return result


def main() -> None:
    research_rows = read_jsonl(INDEX / "overture_action_research.jsonl")
    event_rows = read_jsonl(INDEX / "overture_events.jsonl")
    candidate_rows = read_jsonl(INDEX / "overture_action_candidates.jsonl")
    review_rows = read_jsonl(INDEX / "overture_action_candidate_reviews.jsonl")
    corrections = read_jsonl(INDEX / "overture_catalogue_corrections.jsonl")
    page_map = json.loads((INDEX / "overture_pages_map.json").read_text(encoding="utf-8"))
    catalogue = catalogue_rows(INDEX / "OVERTURES.md", page_map)
    gates = read_gates()

    # The reconciled catalogue's stable keys are the record-ID entries in the
    # page map. Joining by number alone would merge reused overture numbers.
    catalogue_ids = {
        key for key in page_map
        if key.startswith("overture:") and isinstance(page_map[key], str)
    }
    research = {row["record_id"]: row for row in research_rows}
    events = {row["record_id"]: row for row in event_rows}
    corrections_by_id = {row["record_id"]: row for row in corrections if row.get("record_id")}

    candidates_by_ga: dict[int, list[dict]] = defaultdict(list)
    for candidate in candidate_rows:
        ga = candidate.get("ga_ordinal") or ga_from_volume(candidate.get("source_volume", ""))
        if ga:
            candidates_by_ga[int(ga)].append(candidate)
    reviews = {row.get("candidate_id"): row for row in review_rows if row.get("candidate_id")}
    candidate_ids = {row.get("candidate_id") for row in candidate_rows}
    orphan_reviews_by_ga: Counter = Counter()
    for candidate_id in reviews.keys() - candidate_ids:
        match = re.match(r"ga(\d+)_", candidate_id or "")
        if match:
            orphan_reviews_by_ga[int(match.group(1))] += 1

    all_record_ids = sorted(catalogue_ids | set(research) | set(events))
    record_rows = []
    records_by_ga: dict[int, list[dict]] = defaultdict(list)
    for record_id in all_record_ids:
        row = research.get(record_id, {})
        catalogue_row = catalogue.get(record_id, {})
        event_bundle = events.get(record_id, {})
        path = page_map.get(record_id, "")
        parts = record_id.split(":")
        vol = row.get("vol") or (parts[1] if len(parts) > 2 else "")
        ga = int(row.get("ga_ordinal") or ga_from_volume(vol) or 0)
        page_match = re.search(r":p(\d+)$", record_id)
        candidate_links = [
            candidate for candidate in candidates_by_ga.get(ga, [])
            if record_id in reviews.get(candidate.get("candidate_id"), {}).get("linked_record_ids", [])
        ]
        explicit_reviewed = len(candidate_links)
        count = len(event_bundle.get("events", []))
        action_ga = max(
            (ga_from_volume(e.get("source_volume", "")) or ga for e in event_bundle.get("events", [])),
            default=None,
        )
        status = row.get("research_status", "not_researched")
        next_record_step = {
            "not_researched": "Research the submitted overture and trace its recorded actions through terminal disposition.",
            "in_progress": "Continue tracing the action trail; use gap_note to resume the source search.",
            "complete": "No overture-level research remains; packet audits and closeout are tracked at GA level.",
            "source_unavailable": "Preserve the documented source gap; do not infer missing actions.",
        }.get(status, "Review the research status and determine the next evidence step.")
        anomaly = []
        if record_id not in catalogue_ids:
            anomaly.append("not_in_reconciled_catalogue")
        if record_id not in research:
            anomaly.append("missing_research_row")
        if record_id in catalogue_ids and record_id not in events:
            anomaly.append("missing_event_bundle")
        correction = corrections_by_id.get(record_id, {})
        output = {
            "ga_ordinal": ga,
            "year": row.get("year", ""),
            "record_id": record_id,
            "number": row.get("number", parts[2] if len(parts) > 3 else ""),
            "source_page": row.get("source_page", page_match.group(1) if page_match else ""),
            "source": row.get("source", catalogue_row.get("source", "")),
            "title": row.get("title", catalogue_row.get("title", "")),
            "disposition": catalogue_row.get("disposition", ""),
            "page": path,
            "research_status": status,
            "next_step": next_record_step,
            "event_count": count,
            "last_action_ga": action_ga or "",
            "search_through_assembly": row.get("search_through_assembly", ""),
            "gap_note": row.get("gap_note", ""),
            "reviewed_candidates_linked": explicit_reviewed,
            "identity_correction": correction.get("action", ""),
            "anomalies": ";".join(anomaly),
        }
        record_rows.append(output)
        records_by_ga[ga].append(output)

    assembly_rows = []
    for ga in range(1, 53):
        records = records_by_ga.get(ga, [])
        candidates = candidates_by_ga.get(ga, [])
        reviewed_candidates = [c for c in candidates if c.get("candidate_id") in reviews]
        invalid_links = sum(
            1 for c in reviewed_candidates
            if any(record_id not in catalogue_ids for record_id in reviews[c["candidate_id"]].get("linked_record_ids", []))
        )
        status_counts = Counter(r["research_status"] for r in records)
        missing_bundles = sum(1 for r in records if "missing_event_bundle" in r["anomalies"])
        catalogue_only = sum(1 for r in records if "missing_research_row" in r["anomalies"])
        gate = gates.get(str(ga), {})
        researched_started = any(s != "not_researched" for s in status_counts)
        reviewed_started = bool(reviewed_candidates)
        gate_started = any(
            gate.get(name, "") not in ("", "unverified")
            for name in ("roster_reconciled", "event_source_audited", "build",
                         "preview_reviewed", "commit_sha", "pushed", "blocker")
        )
        gates_verified = (
            gate.get("roster_reconciled", "").startswith("verified")
            and gate.get("event_source_audited", "").startswith("verified")
            and gate.get("build", "").startswith("passed:")
            and gate.get("preview_reviewed", "").startswith("verified")
            and bool(re.fullmatch(r"[0-9a-fA-F]{7,40}", gate.get("commit_sha", "")))
            and gate.get("pushed") in (True, "true", "pushed")
        )
        records_clear = bool(records) and all(
            r["research_status"] in ("complete", "source_unavailable")
            and "missing_event_bundle" not in r["anomalies"]
            and (r["research_status"] != "source_unavailable" or bool(r["gap_note"].strip()))
            for r in records
        ) and catalogue_only == 0
        candidates_clear = (len(reviewed_candidates) == len(candidates)
                            and invalid_links == 0
                            and orphan_reviews_by_ga[ga] == 0)
        if records_clear and candidates_clear and gates_verified:
            ga_status = "closed"
        elif researched_started or reviewed_started or gate_started:
            ga_status = "in_progress"
        else:
            ga_status = "open"
        blocker_parts = []
        if not records_clear:
            if status_counts["in_progress"]:
                blocker_parts.append(f"{status_counts['in_progress']} records in progress")
            if status_counts["not_researched"]:
                blocker_parts.append(f"{status_counts['not_researched']} records not researched")
            if missing_bundles:
                blocker_parts.append(f"{missing_bundles} missing event bundles")
            if catalogue_only:
                blocker_parts.append(f"{catalogue_only} catalogue records missing research rows")
        if len(reviewed_candidates) != len(candidates):
            blocker_parts.append(f"{len(candidates) - len(reviewed_candidates)} candidates unreviewed")
        if invalid_links:
            blocker_parts.append(f"{invalid_links} invalid candidate links")
        if orphan_reviews_by_ga[ga]:
            blocker_parts.append(f"{orphan_reviews_by_ga[ga]} orphaned candidate reviews")
        if not gates_verified:
            for gate_name in ("roster_reconciled", "event_source_audited", "build",
                              "preview_reviewed", "commit_sha", "pushed"):
                value = gate.get(gate_name, "")
                verified = (
                    value.startswith("verified") if gate_name in ("roster_reconciled", "event_source_audited", "preview_reviewed")
                    else value.startswith("passed:") if gate_name == "build"
                    else bool(re.fullmatch(r"[0-9a-fA-F]{7,40}", value)) if gate_name == "commit_sha"
                    else value in (True, "true", "pushed")
                )
                if not verified:
                    blocker_parts.append(f"{gate_name} unverified")
        if gate.get("blocker"):
            blocker_parts.append(gate["blocker"])
        assembly_rows.append({
            "ga_ordinal": ga,
            "assembly": f"GA{ga}",
            "status": ga_status,
            "catalogue_records": len([r for r in records if "not_in_reconciled_catalogue" not in r["anomalies"]]),
            "records_complete": status_counts["complete"],
            "records_in_progress": status_counts["in_progress"],
            "records_not_researched": status_counts["not_researched"],
            "records_source_unavailable": status_counts["source_unavailable"],
            "missing_research_rows": catalogue_only,
            "missing_event_bundles": missing_bundles,
            "candidate_passages": len(candidates),
            "candidates_reviewed": len(reviewed_candidates),
            "candidates_unreviewed": len(candidates) - len(reviewed_candidates),
            "candidate_reviews_orphaned": orphan_reviews_by_ga[ga],
            "candidate_invalid_links": invalid_links,
            "roster_reconciled": gate.get("roster_reconciled", "unverified"),
            "event_source_audited": gate.get("event_source_audited", "unverified"),
            "build": gate.get("build", "unverified"),
            "preview_reviewed": gate.get("preview_reviewed", "unverified"),
            "commit_sha": gate.get("commit_sha", ""),
            "pushed": gate.get("pushed", "unverified"),
            "blocker": "; ".join(blocker_parts),
        })

    # Repeat the parent Assembly status on each record row so the overture
    # sheet can be filtered/grouped on its own without losing packet status.
    assembly_status_by_ga = {row["ga_ordinal"]: row["status"] for row in assembly_rows}
    for row in record_rows:
        row["assembly_status"] = assembly_status_by_ga.get(row["ga_ordinal"], "open")

    # Keep spreadsheet exports human-scannable: O1, O2, ... O10 within each GA.
    # The stable record ID remains the final tie-breaker for reused numbers.
    record_rows.sort(key=lambda row: (
        int(row["ga_ordinal"] or 0),
        int(row["number"] or 0),
        int(row["source_page"] or 0),
        row["record_id"],
    ))

    csv_write(RECORD_OUT, [
        "ga_ordinal", "assembly_status", "year", "record_id", "number", "source_page", "source", "title", "page",
        "research_status", "next_step", "disposition", "event_count", "last_action_ga", "search_through_assembly", "gap_note",
        "reviewed_candidates_linked",
        "identity_correction", "anomalies",
    ], record_rows)
    csv_write(ASSEMBLY_OUT, [
        "ga_ordinal", "assembly", "status", "catalogue_records", "records_complete",
        "records_in_progress", "records_not_researched", "records_source_unavailable",
        "missing_research_rows", "missing_event_bundles", "candidate_passages", "candidates_reviewed",
        "candidates_unreviewed", "candidate_invalid_links", "candidate_reviews_orphaned",
        "roster_reconciled", "event_source_audited",
        "build", "preview_reviewed", "commit_sha", "pushed", "blocker",
    ], assembly_rows)

    # Prioritize the explicitly requested cleanup sequence, then remaining
    # trail gaps, early action-trail audits, known roster discrepancies,
    # candidate coverage, and packet closeout. Keep GA51 and GA52 in the work
    # window; GA52 trails remain in progress until later primary actions are
    # available. GA4-GA7 get a focused audit after the record/link cleanup
    # priorities and before general candidate coverage.
    queue_rows = []
    in_scope = [r for r in assembly_rows if r["ga_ordinal"] < 53]
    def work_priority(assembly):
        if assembly["records_in_progress"]:
            return 0
        if assembly["records_source_unavailable"]:
            return 1
        if assembly["candidate_invalid_links"]:
            return 2
        if assembly["candidate_reviews_orphaned"]:
            return 3
        if assembly["records_not_researched"] or assembly["missing_research_rows"] or assembly["missing_event_bundles"]:
            return 4
        if assembly["ga_ordinal"] in (4, 5, 6, 7) and (
            assembly["candidates_unreviewed"] or assembly["event_source_audited"] == "unverified"
        ):
            return 5
        if re.search(r"roster reconciliation open", assembly["blocker"], re.IGNORECASE):
            return 6
        if assembly["candidates_unreviewed"]:
            return 7
        return 8

    for queue_order, assembly in enumerate(sorted(
        in_scope,
        key=lambda r: (work_priority(r), r["ga_ordinal"] if work_priority(r) == 5 else -r["ga_ordinal"]),
    ), 1):
        ga = assembly["ga_ordinal"]
        if assembly["records_in_progress"]:
            step = (
                f"Complete source trails for {assembly['records_in_progress']} overture records; "
                "then document evidence-based source gaps."
            )
            phase = "records_in_progress"
        elif assembly["records_source_unavailable"]:
            step = f"Investigate and document {assembly['records_source_unavailable']} source-unavailable overture records."
            phase = "records_source_unavailable"
        elif assembly["candidate_invalid_links"]:
            step = f"Repair {assembly['candidate_invalid_links']} invalid candidate links."
            phase = "candidate_invalid_links"
        elif assembly["candidate_reviews_orphaned"]:
            step = f"Resolve {assembly['candidate_reviews_orphaned']} orphaned candidate reviews."
            phase = "candidate_reviews_orphaned"
        elif assembly["records_not_researched"] or assembly["missing_research_rows"] or assembly["missing_event_bundles"]:
            step = (
                f"Complete {assembly['records_not_researched']} unresearched records; "
                f"restore {assembly['missing_research_rows']} missing research rows and "
                f"{assembly['missing_event_bundles']} missing event bundles."
            )
            phase = "action_trails"
        elif ga in (4, 5, 6, 7) and (
            assembly["candidates_unreviewed"] or assembly["event_source_audited"] == "unverified"
        ):
            step = (
                f"Audit GA{ga} action trails against the remaining {assembly['candidates_unreviewed']} "
                "unreviewed candidate passages; confirm each passage is linked to the correct overture "
                "or document why it is unrelated."
            )
            phase = "early_action_trail_audit"
        elif re.search(r"roster reconciliation open", assembly["blocker"], re.IGNORECASE):
            step = (
                f"Reconcile {assembly['assembly']} roster against its minutes docket, "
                "including reused numbers and source-page identities."
            )
            phase = "roster_reconciliation"
        elif assembly["candidates_unreviewed"]:
            step = (
                f"Review {assembly['candidates_unreviewed']} remaining candidate passages."
            )
            phase = "candidate_coverage"
        else:
            pending_gates = [
                key for key in ("roster_reconciled", "event_source_audited", "build",
                                "preview_reviewed", "commit_sha", "pushed")
                if key == "commit_sha" and not re.fullmatch(r"[0-9a-fA-F]{7,40}", assembly[key] or "")
                or key == "pushed" and assembly[key] not in (True, "true", "pushed")
                or key in ("roster_reconciled", "event_source_audited", "preview_reviewed")
                   and not (assembly[key] or "").startswith("verified")
                or key == "build" and not (assembly[key] or "").startswith("passed:")
            ]
            step = "Complete packet closeout: " + ", ".join(pending_gates) + "." if pending_gates else "No remaining work recorded."
            phase = "packet_closeout" if pending_gates else "done"
        queue_rows.append({
            "queue_order": queue_order,
            "scope": "assembly_packet",
            "assembly": assembly["assembly"],
            "status": assembly["status"],
            "phase": phase,
            "records_complete_total": f"{assembly['records_complete'] + assembly['records_source_unavailable']}/{assembly['catalogue_records']}",
            "candidates_reviewed_total": f"{assembly['candidates_reviewed']}/{assembly['candidate_passages']}",
            "next_step": step,
            "follow_up": "",
        })
    inventory_rows = []
    if INVENTORY_RECONCILIATION.exists():
        with INVENTORY_RECONCILIATION.open(encoding="utf-8-sig", newline="") as stream:
            inventory_rows = list(csv.DictReader(stream))
    inventory_statuses = Counter(row.get("review_status", "unreviewed") for row in inventory_rows)
    inventory_unreviewed = inventory_statuses.get("unreviewed", 0)
    inventory_resolved = len(inventory_rows) - inventory_unreviewed
    baseline_commit = inventory_rows[0].get("baseline_commit", "") if inventory_rows else ""
    current_snapshot = inventory_rows[0].get("current_snapshot_commit", "") if inventory_rows else ""
    current_only = sum(row.get("delta_type") == "current_only" for row in inventory_rows)
    baseline_only = sum(row.get("delta_type") == "baseline_only" for row in inventory_rows)
    shared_ids = len(catalogue_ids) - current_only
    baseline_total = shared_ids + baseline_only
    resolution_summary = ", ".join(
        f"{count} {status.replace('_', ' ')}"
        for status, count in sorted(inventory_statuses.items())
        if status != "unreviewed"
    ) or "none"

    queue_rows.extend([
        {
            "queue_order": len(queue_rows) + 1,
            "scope": "project_wide",
            "assembly": "All GAs",
            "status": "open",
            "phase": "inventory_reconciliation",
            "records_complete_total": "",
            "candidates_reviewed_total": "",
            "next_step": f"Review {inventory_unreviewed} of {len(inventory_rows)} unresolved identity deltas in inventory-reconciliation.csv against the cited source pages. Classify each as a distinct proposal, locator correction, reprint/duplicate, or locator-only occurrence.",
            "follow_up": f"Snapshot {baseline_commit} ({baseline_total} IDs) to {current_snapshot} ({len(catalogue_ids)} IDs): {shared_ids} shared, {current_only} current-only, {baseline_only} baseline-only. Reviewed {inventory_resolved}/{len(inventory_rows)} deltas ({resolution_summary}); possible subject matches are leads only. Preserve verified proposals and reused numbers.",
        },
        {
            "queue_order": len(queue_rows) + 2,
            "scope": "project_wide",
            "assembly": "All GAs",
            "status": "open",
            "phase": "completion_audit",
            "records_complete_total": "",
            "candidates_reviewed_total": "",
            "next_step": "Audit every in-scope distinct record, source quote, page anchor, chronological order, and rendered page; run the full validating site build after the last Assembly packet.",
            "follow_up": "Active work window: GA1-GA52. GA52 has 19 trails in progress that need later primary actions or reports; keep them open until the supporting minutes are available.",
        },
    ])
    csv_write(QUEUE_OUT, [
        "queue_order", "scope", "assembly", "status", "phase", "records_complete_total",
        "candidates_reviewed_total", "next_step", "follow_up",
    ], queue_rows)
    write_hierarchical_tracker(assembly_rows, records_by_ga, queue_rows, TRACKER_OUT)
    print(f"Generated {TRACKER_OUT}, {RECORD_OUT} ({len(record_rows)} rows), {ASSEMBLY_OUT} ({len(assembly_rows)} rows), and {QUEUE_OUT} ({len(queue_rows)} rows).")


